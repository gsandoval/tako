package codegen

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/gsandoval/tako/pkg/analyzer"
)

// GenerateCfire emits .tako/gen/<service>/main.cf and the harness for cfire applications.
func GenerateCfire(g *analyzer.AppGraph, dir string) ([]string, error) {
	var written []string
	for _, svc := range g.Services {
		rel := filepath.Join(".tako", "gen", svc.Name, "main.cf")
		path := filepath.Join(dir, rel)

		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return nil, err
		}

		var b strings.Builder
		fmt.Fprintf(&b, "// Code generated by tako. DO NOT EDIT.\n")
		fmt.Fprintf(&b, "//\n// Service %s, generated from the app's declarations.\n", svc.Name)
		fmt.Fprintf(&b, "package main\n\n")
		fmt.Fprintf(&b, "import \"core:tako\"\n")
		fmt.Fprintf(&b, "import \"core:json\"\n")
		fmt.Fprintf(&b, "import %s \"../..\"\n\n", svc.Package)

		fmt.Fprintf(&b, "fn main() -> i32 {\n")
		fmt.Fprintf(&b, "    tako.boot()\n\n")

		// Register entity schemas
		for _, r := range g.Resources {
			if r.Kind == "entity" {
				idxs := strings.Join(r.Indexes, ",")
				fmt.Fprintf(&b, "    tako.register_entity(%q, \"id\", %q, \"[]\")\n", r.Name, idxs)
			}
		}
		if len(g.Resources) > 0 {
			b.WriteString("\n")
		}

		var decoders []analyzer.Handler

		// Mount routes
		for _, h := range g.Handlers {
			if h.Service != svc.Name {
				continue
			}
			if h.Kind == "api" || h.Kind == "page" {
				decName := fmt.Sprintf("decode_%s", analyzer.ShortVar(h))
				decoders = append(decoders, h)

				fmt.Fprintf(&b, "    // %s %s\n", h.Kind, h.Route)
				fmt.Fprintf(&b, "    tako.mount_json(%q, |req: tako.HttpReq| -> tako.HttpRes! {\n", h.Route)
				fmt.Fprintf(&b, "        decoded := try %s(req)\n", decName)
				fmt.Fprintf(&b, "        ctx := tako.ctx_from_req(req)\n")
				fmt.Fprintf(&b, "        res := try %s.%s(ctx, decoded)\n", svc.Package, analyzer.ShortVar(h))
				fmt.Fprintf(&b, "        return tako.json_res(200, json.stringify_struct(res))\n")
				fmt.Fprintf(&b, "    }, tako.MountOpts{})\n\n")
			} else if h.Kind == "worker" {
				fmt.Fprintf(&b, "    // worker %s (%s)\n", analyzer.ShortVar(h), h.Binding)
				fmt.Fprintf(&b, "    tako.register_worker(%q, %q, |ctx: tako.Ctx, payload: str| -> void! {\n",
					analyzer.ShortVar(h), h.Binding)
				fmt.Fprintf(&b, "        msg := try json.parse_struct[%s.%s](payload)\n", svc.Package, h.Binding)
				fmt.Fprintf(&b, "        try %s.%s(ctx, msg)\n", svc.Package, analyzer.ShortVar(h))
				fmt.Fprintf(&b, "    })\n\n")
			} else if h.Kind == "cron" {
				fmt.Fprintf(&b, "    // cron %s (%s)\n", analyzer.ShortVar(h), h.Schedule)
				fmt.Fprintf(&b, "    tako.register_cron(%q, %q, true, |ctx: tako.Ctx| -> void! {\n",
					analyzer.ShortVar(h), h.Schedule)
				fmt.Fprintf(&b, "        try %s.%s(ctx)\n", svc.Package, analyzer.ShortVar(h))
				fmt.Fprintf(&b, "    })\n\n")
			}
		}

		fmt.Fprintf(&b, "    return tako.serve(tako.ServeOpts{})\n")
		fmt.Fprintf(&b, "}\n\n")

		// Emit decoders
		for _, h := range decoders {
			decName := fmt.Sprintf("decode_%s", analyzer.ShortVar(h))
			fmt.Fprintf(&b, "fn %s(req: tako.HttpReq) -> %s.%s! {\n", decName, svc.Package, h.ReqType)
			fmt.Fprintf(&b, "    mut out := %s.%s{}\n", svc.Package, h.ReqType)
			if h.HasBody {
				fmt.Fprintf(&b, "    if req.body != \"\" {\n")
				fmt.Fprintf(&b, "        out = try json.parse_struct[%s.%s](req.body)\n", svc.Package, h.ReqType)
				fmt.Fprintf(&b, "    }\n")
			}
			for _, bind := range h.Bindings {
				if bind.Kind == "path" {
					fmt.Fprintf(&b, "    out.%s = req.path_string(%q)\n", bind.Field, bind.Name)
				}
			}
			fmt.Fprintf(&b, "    return out\n")
			fmt.Fprintf(&b, "}\n\n")
		}

		if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
			return nil, err
		}
		written = append(written, rel)

		// Emit test harness
		hrel := filepath.Join(".tako", "gen", svc.Name, "harness", "tako_harness.cf")
		hpath := filepath.Join(dir, hrel)
		if err := os.MkdirAll(filepath.Dir(hpath), 0o755); err != nil {
			return nil, err
		}
		var hb strings.Builder
		fmt.Fprintf(&hb, "// Code generated by tako. DO NOT EDIT.\n")
		fmt.Fprintf(&hb, "package %s\n\n", svc.Package)
		fmt.Fprintf(&hb, "import \"core:tako\"\n\n")
		fmt.Fprintf(&hb, "// Test harness hook for cfire test\n")
		if err := os.WriteFile(hpath, []byte(hb.String()), 0o644); err != nil {
			return nil, err
		}
		written = append(written, hrel)
	}

	return written, nil
}
