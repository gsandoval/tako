package codegen

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/gsandoval/tako/pkg/analyzer"
)

// Generate writes one main package per service under dir/.tako/gen/ and
// returns the written file paths, relative to dir. Output is gofmt-clean
// and meant to be read: one visible line per endpoint, a plain decode
// function per request struct, stdlib routing, no reflection.
func Generate(g *analyzer.AppGraph, dir string) ([]string, error) {
	var written []string
	for _, svc := range g.Services {
		src, err := serviceMain(g, svc)
		if err != nil {
			return nil, err
		}
		rel := filepath.Join(".tako", "gen", svc.Name, "main.go")
		path := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return nil, err
		}
		if err := os.WriteFile(path, src, 0o644); err != nil {
			return nil, err
		}
		written = append(written, rel)
	}
	return written, nil
}

// serviceMain renders the generated main package for one service.
func serviceMain(g *analyzer.AppGraph, svc analyzer.Service) ([]byte, error) {
	alias := pkgAlias(svc)
	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by tako. DO NOT EDIT.
//
// Service %s, generated from the app's declarations. This file is meant to
// be read; to change it, change the app (or the generator), never this
// output.
package main

import (
	"net/http"

	runtime "github.com/gsandoval/tako/pkg/runtime"

	%s %q
)

func main() {
`, svc.Name, alias, svc.Package)

	if hasResources(g, svc) {
		b.WriteString("\truntime.Boot() // wire backends: local under .tako/data, gcp from Phase E\n\n")
	}
	b.WriteString("\tmux := http.NewServeMux()\n\n")

	var decoders []analyzer.Handler
	for _, h := range g.Handlers {
		if h.Service != svc.Name {
			continue
		}
		decode := "nil"
		if needsDecode(h) {
			decode = decodeName(h)
			decoders = append(decoders, h)
		}
		wrapper := "JSONHandler"
		if h.ResBlob {
			wrapper = "BlobHandler"
		}
		fmt.Fprintf(&b, "\t// %s → %s (%s)\n", h.Route, h.Var, analyzer.ShortPos(h.Pos))
		fmt.Fprintf(&b, "\tmux.Handle(%q, runtime.%s(%s.%s, %s))\n\n",
			h.Route, wrapper, alias, analyzer.ShortVar(h), decode)
	}

	b.WriteString("\truntime.Serve(mux)\n}\n")

	for _, h := range decoders {
		writeDecoder(&b, alias, h)
	}

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("generated main for service %s does not format: %w", svc.Name, err)
	}
	return src, nil
}

// writeDecoder renders the static request-binding function for one
// endpoint.
func writeDecoder(b *strings.Builder, alias string, h analyzer.Handler) {
	reqType := alias + "." + h.ReqType
	fmt.Fprintf(b, "\n// %s binds %s requests to %s.\n", decodeName(h), h.Route, reqType)
	fmt.Fprintf(b, "func %s(r *http.Request) (%s, error) {\n", decodeName(h), reqType)
	fmt.Fprintf(b, "\tvar req %s\n", reqType)
	if fallible(h) {
		b.WriteString("\tvar err error\n")
	}
	if h.HasBody {
		b.WriteString("\tif err := runtime.DecodeJSON(r, &req); err != nil {\n\t\treturn req, err\n\t}\n")
	}
	for _, bind := range h.Bindings {
		helper := helperName(bind)
		if bind.Type == "string" {
			fmt.Fprintf(b, "\treq.%s = runtime.%s(r, %q)\n", bind.Field, helper, bind.Name)
			continue
		}
		fmt.Fprintf(b, "\tif req.%s, err = runtime.%s(r, %q); err != nil {\n\t\treturn req, err\n\t}\n",
			bind.Field, helper, bind.Name)
	}
	b.WriteString("\treturn req, nil\n}\n")
}

// helperName maps a binding to its pkg/runtime helper.
func helperName(b analyzer.Binding) string {
	if b.Kind == "blob" {
		return "FormBlob"
	}
	kind := map[string]string{"path": "Path", "query": "Query", "form": "Form"}[b.Kind]
	typ := map[string]string{
		"string":  "String",
		"bool":    "Bool",
		"int":     "Int",
		"int64":   "Int64",
		"float64": "Float64",
	}[b.Type]
	return kind + typ
}

// hasResources reports whether the service's package declares resources
// needing a booted backend.
func hasResources(g *analyzer.AppGraph, svc analyzer.Service) bool {
	for _, r := range g.Resources {
		if r.Package == svc.Package {
			return true
		}
	}
	return false
}

func needsDecode(h analyzer.Handler) bool {
	return h.ReqType != "" && (h.HasBody || len(h.Bindings) > 0)
}

// fallible reports whether any non-body binding can fail (string bindings
// cannot; blob and parsed bindings can).
func fallible(h analyzer.Handler) bool {
	for _, b := range h.Bindings {
		if b.Type != "string" || b.Kind == "blob" {
			return true
		}
	}
	return false
}

func decodeName(h analyzer.Handler) string {
	return "decode" + analyzer.ShortVar(h)
}

// pkgAlias is the import alias for the service's user package in generated
// code.
func pkgAlias(svc analyzer.Service) string {
	if i := strings.LastIndex(svc.Package, "/"); i >= 0 {
		return svc.Package[i+1:]
	}
	return svc.Package
}
