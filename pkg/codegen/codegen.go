// asyncServiceMain renders the main for a worker/subscriber service: it
// registers its one handler on the wired backend (local mode consumes
// in-process) and serves the push endpoint deliveries arrive on in the
// cloud (Pub/Sub push lands here in Phase F).
func asyncServiceMain(g *analyzer.AppGraph, svc analyzer.Service) ([]byte, error) {
	alias := pkgAlias(g, svc)
	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by tako. DO NOT EDIT.
//
// Service %s, generated from the app's declarations. This file is meant to
// be read; to change it, change the app (or the generator), never this
// output.
package main

import (
	"net/http"

	runtime "github.com/gsandoval/tako/pkg/runtime"

	%s %q
)

func main() {
	runtime.Boot() // wire backends: local under .tako/data, gcp from Phase E

	// A worker declares no routes of its own, so this mux holds only
	// tako's reserved endpoints and is served directly.
	takoMux := http.NewServeMux()

`, svc.Name, alias, svc.Package)

	for _, h := range g.Handlers {
		if h.Service != svc.Name {
			continue
		}
		register := "RegisterWorker"
		if h.Kind == "subscribe" {
			register = "RegisterSubscriber"
		}
		fmt.Fprintf(&b, "\t// %s\n", analyzer.HandlerLine(h))
		fmt.Fprintf(&b, "\truntime.%s(%q, %s.%s)\n", register, analyzer.ShortVar(h), alias, analyzer.ShortVar(h))
		fmt.Fprintf(&b, "\t// Cloud deliveries arrive as pushes: 204 acks, 500 retries, 400 = permanent.\n")
		fmt.Fprintf(&b, "\ttakoMux.Handle(%q, runtime.PushHandler(%q, %s.%s))\n\n",
			routes.PatternPush, analyzer.ShortVar(h), alias, analyzer.ShortVar(h))
	}

	b.WriteString("\truntime.Serve(takoMux)\n}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("generated main for service %s does not format: %w", svc.Name, err)
	}
	return src, nil
}

// serviceMain renders the generated main package for one service.
func serviceMain(g *analyzer.AppGraph, svc analyzer.Service) ([]byte, error) {
	alias := pkgAlias(g, svc)
	site := siteOf(g, svc)
	usesApp := statusOf(g, svc) != nil // the status page is named from here too
	for _, h := range g.Handlers {
		if h.Service == svc.Name || h.Package == svc.Package {
			usesApp = true
		}
	}
	callees := remoteCallees(g, svc)
	callBlock, callNetURL := "", false
	if len(callees) > 0 {
		callBlock, callNetURL = remoteCallBlock(callees)
	}

	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by tako. DO NOT EDIT.
//
// Service %s, generated from the app's declarations. This file is meant to
// be read; to change it, change the app (or the generator), never this
// output.
package main

import (
`, svc.Name)
	if site != nil {
		b.WriteString("\t\"embed\"\n")
	}
	if strings.Contains(callBlock, "fmt.Sprint") {
		b.WriteString("\t\"fmt\"\n")
	}
	if site != nil {
		b.WriteString("\t\"io/fs\"\n")
	}
	b.WriteString("\t\"net/http\"\n")
	if callNetURL {
		b.WriteString("\tneturl \"net/url\"\n")
	}
	if len(callees) > 0 {
		b.WriteString("\t\"os\"\n")
	}
	b.WriteString("\n")
	if len(callees) > 0 {
		b.WriteString("\ttako \"github.com/gsandoval/tako\"\n")
	}
	b.WriteString("\truntime \"github.com/gsandoval/tako/pkg/runtime\"\n")
	if usesApp {
		fmt.Fprintf(&b, "\n\t%s %q\n", alias, svc.Package)
	}
	calleePkgs := map[string]string{}
	for _, c := range callees {
		calleePkgs[c.handler.Package] = c.service
	}
	for _, c := range callees {
		if calleePkgs[c.handler.Package] != "" && c.handler.Package != svc.Package {
			fmt.Fprintf(&b, "\t%s %q\n", calleePkgs[c.handler.Package], c.handler.Package)
			calleePkgs[c.handler.Package] = ""
		}
	}
	b.WriteString(")\n\n")
	if site != nil {
		fmt.Fprintf(&b, "// The site (%s) is embedded at build time — the binary IS the\n// deployment, so rollback rolls the site back too.\n", site.Name)
		b.WriteString("//\n//go:embed all:site\nvar siteFS embed.FS\n\n")
	}
	b.WriteString("func main() {\n")

	// Unconditional (RC3). The guard this replaces asked "does this
	// service have backends to wire", which is the right question for
	// backends and the wrong one for everything else Boot installs:
	// Cloud Logging (so lines carry a severity and a trace) and the
	// request metrics every service is supposed to export. A
	// resource-less service got none of it — hello deployed with no
	// severity on any line and no requests/request_ms at all, so an
	// alert built on them watched a series nothing wrote.
	b.WriteString("\truntime.Boot() // observability always; backends when this package declares any\n\n")
	b.WriteString(callBlock)
	for _, r := range g.Resources {
		if r.Package == svc.Package && r.Kind == "queue" && r.RateLimit > 0 {
			fmt.Fprintf(&b, "\t// queue %s: WithDelivery RateLimit %d — Cloud Tasks caps dispatch\n\t// in the cloud; locally the dispatcher paces to the same rate.\n", r.Name, r.RateLimit)
			fmt.Fprintf(&b, "\truntime.SetQueueRate(%q, %d)\n\n", r.Name, r.RateLimit)
		}
	}
	if reserved := hasAuth(g) || hasBucket(g, svc) || hasCron(g, svc); reserved {
		b.WriteString("\t// tako's own endpoints, on a mux of their own. They are answered\n")
		b.WriteString("\t// before the app's router below is consulted, so nothing under\n")
		b.WriteString("\t// /_tako/ can be shadowed by a route this app declares — and no\n")
		b.WriteString("\t// framework pattern can collide with a wildcard page, which on one\n")
		b.WriteString("\t// shared mux is a panic at startup rather than a bad response.\n")
		b.WriteString("\ttakoMux := http.NewServeMux()\n")
		if hasAuth(g) {
			b.WriteString("\n\t// Auth (tako.Auth): the session endpoint — sign-in posts the\n\t// Identity Platform ID token here once; sessions are revocable\n\t// records in the entity store. The signout form is the dev bar's.\n")
			b.WriteString("\t//\n\t// The declared providers ride along: a session may only come from\n\t// one of them, whatever else the Identity Platform project has\n\t// enabled.\n")
			fmt.Fprintf(&b, "\ttakoMux.Handle(%q, runtime.SessionHandler(%s))\n", routes.PatternSession, providerArgs(g))
			fmt.Fprintf(&b, "\ttakoMux.Handle(%q, runtime.SignOutHandler())\n", routes.PatternSignOut)
			fmt.Fprintf(&b, "\ttakoMux.Handle(%q, runtime.SignInPage(%s))\n", routes.PatternSignIn, providerArgs(g))
			// The declared roles, for the dev sign-in page. There is no
			// Identity Platform on a laptop to hold a custom claim, so
			// locally a role is something you tick before signing in —
			// deliberately, because a local session that carried every
			// role would make the refusal path unreachable in dev.
			if len(g.Roles) > 0 {
				fmt.Fprintf(&b, "\truntime.RegisterRoles(%s) // tako.Role declarations; the dev sign-in page offers them\n", quotedList(g.Roles))
			}
		}
		if hasBucket(g, svc) {
			b.WriteString("\n\t// Signed upload/download URLs land here (SignedPut/SignedGet).\n")
			fmt.Fprintf(&b, "\ttakoMux.Handle(%q, runtime.SignedURLHandler())\n", routes.PatternSigned)
		}
		if hasCron(g, svc) {
			b.WriteString("\n\t// Cloud Scheduler triggers crons here (T2); the request proves\n\t// itself with a Google-signed OIDC token — locally the in-process\n\t// ticker drives them and this route just refuses strangers.\n")
			fmt.Fprintf(&b, "\ttakoMux.Handle(%q, runtime.CronDispatch())\n", routes.PatternCron)
		}
		b.WriteString("\n")
	}
	// The status page is registered before anything can answer: every
	// response tako produces for itself renders through it (FL11).
	if sp := statusOf(g, svc); sp != nil {
		fmt.Fprintf(&b, "\t// %s answers every response this service produces itself —\n\t// 404, 403, 405, 500 — so they wear the app rather than plain text.\n", sp.Var)
		fmt.Fprintf(&b, "\truntime.RegisterStatusPage(%s.%s)\n\n", alias, analyzer.ShortName(sp.Var))
	}
	b.WriteString("\tmux := http.NewServeMux()\n\n")
	if site != nil {
		fmt.Fprintf(&b, "\t// site %s: declared routes win (more specific patterns); the site\n\t// serves everything else with §2.11's headers. Its templates/ back\n\t// site.Render and are never served statically.\n", site.Name)
		b.WriteString("\tsiteRoot, err := fs.Sub(siteFS, \"site\")\n\tif err != nil {\n\t\tpanic(err)\n\t}\n")
		fmt.Fprintf(&b, "\truntime.RegisterSiteTemplates(siteRoot, runtime.SiteOptions{%s})\n", siteOptionsLiteral(site))
		fmt.Fprintf(&b, "\tmux.Handle(\"/\", runtime.SiteHandler(siteRoot, runtime.SiteOptions{%s}))\n\n", siteOptionsLiteral(site))
	}
	var decoders []analyzer.Handler
	for _, h := range g.Handlers {
		// Routes only: async handlers register below, crons have no route.
		if h.Service != svc.Name || h.Kind == "worker" || h.Kind == "subscribe" || h.Kind == "cron" {
			continue
		}
		decode := "nil"
		if needsDecode(h) {
			decode = decodeName(h)
			decoders = append(decoders, h)
		}
		wrapper := "JSONHandler"
		if h.ResBlob {
			wrapper = "BlobHandler"
		}
		if h.Kind == "page" {
			wrapper = "PageHandler"
		}
		auth := ""
		if h.RequiresAuth {
			auth = ", runtime.RequireAuth()"
		}
		// The policy's NAME, not the handle: Endpoint.Call evaluates the
		// rule (so a cross-service call cannot walk past it), and what
		// the mount adds is the name a status page needs to tell this
		// refusal from a stale CSRF token's.
		if h.Policy != "" {
			auth += fmt.Sprintf(", runtime.RequirePolicy(%q)", h.Policy)
		}
		// Pages and blobs read MaxAge; a JSON handler does not yet, and
		// passing it there would generate a line that says something
		// the runtime ignores.
		if h.MaxAge > 0 && (h.Kind == "page" || h.ResBlob) {
			auth += fmt.Sprintf(", runtime.CacheFor(%d)", h.MaxAge)
		}
		fmt.Fprintf(&b, "\t// %s\n", analyzer.HandlerLine(h))
		fmt.Fprintf(&b, "\tmux.Handle(%q, runtime.%s(%s.%s, %s%s))\n\n",
			muxPattern(h.Route), wrapper, alias, analyzer.ShortVar(h), decode, auth)
	}

	for _, h := range g.Handlers {
		if h.Package != svc.Package {
			continue
		}
		switch h.Kind {
		case "worker":
			fmt.Fprintf(&b, "\t// %s — local mode runs the worker in-process\n", analyzer.HandlerLine(h))
			fmt.Fprintf(&b, "\truntime.RegisterWorker(%q, %s.%s)\n\n", analyzer.ShortVar(h), alias, analyzer.ShortVar(h))
		case "subscribe":
			fmt.Fprintf(&b, "\t// %s — local mode runs the subscriber in-process\n", analyzer.HandlerLine(h))
			fmt.Fprintf(&b, "\truntime.RegisterSubscriber(%q, %s.%s)\n\n", analyzer.ShortVar(h), alias, analyzer.ShortVar(h))
		case "cron":
			fmt.Fprintf(&b, "\t// %s — runs in this service on its schedule\n", analyzer.HandlerLine(h))
			fmt.Fprintf(&b, "\truntime.RegisterCron(%q, %s.%s)\n\n", analyzer.ShortVar(h), alias, analyzer.ShortVar(h))
		case "job":
			fmt.Fprintf(&b, "\t// %s — local mode runs executions in-process (a real Cloud Run Job in the cloud)\n", analyzer.HandlerLine(h))
			fmt.Fprintf(&b, "\truntime.RegisterJob(%q, %s.%s)\n\n", analyzer.ShortVar(h), alias, analyzer.ShortVar(h))
		case "singleton":
			fmt.Fprintf(&b, "\t// %s — local mode runs the loop in-process (its own min=1 service in the cloud)\n", analyzer.HandlerLine(h))
			fmt.Fprintf(&b, "\truntime.RegisterSingleton(%q, %s.%s)\n\n", analyzer.ShortVar(h), alias, analyzer.ShortVar(h))
		}
	}

	served := "mux"
	if hasAuth(g) || hasBucket(g, svc) || hasCron(g, svc) {
		served = "runtime.Reserved(takoMux, mux)"
	}
	if hasAuth(g) {
		fmt.Fprintf(&b, "\truntime.Serve(runtime.WithDevBar(%s)) // the dev bar injects locally only\n}\n", served)
	} else {
		fmt.Fprintf(&b, "\truntime.Serve(%s)\n}\n", served)
	}

	for _, h := range decoders {
		writeDecoder(&b, alias, h)
	}

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("generated main for service %s does not format: %w", svc.Name, err)
	}
	return src, nil
}

// writeDecoder renders the static request-binding function for one
// endpoint.
func writeDecoder(b *strings.Builder, alias string, h analyzer.Handler) {
	reqType := alias + "." + h.ReqType
	fmt.Fprintf(b, "\n// %s binds %s requests to %s.\n", decodeName(h), h.Route, reqType)
	fmt.Fprintf(b, "func %s(r *http.Request) (%s, error) {\n", decodeName(h), reqType)
	fmt.Fprintf(b, "\tvar req %s\n", reqType)
	if fallible(h) {
		b.WriteString("\tvar err error\n")
	}
	if h.HasBody {
		b.WriteString("\tif err := runtime.DecodeJSON(r, &req); err != nil {\n\t\treturn req, err\n\t}\n")
	}
	for _, bind := range h.Bindings {
		helper := helperName(bind)
		if infallibleBinding(bind) {
			fmt.Fprintf(b, "\treq.%s = runtime.%s(r, %q)\n", bind.Field, helper, bind.Name)
			continue
		}
		fmt.Fprintf(b, "\tif req.%s, err = runtime.%s(r, %q); err != nil {\n\t\treturn req, err\n\t}\n",
			bind.Field, helper, bind.Name)
	}
	b.WriteString("\treturn req, nil\n}\n")
}

// helperName maps a binding to its pkg/runtime helper.
func helperName(b analyzer.Binding) string {
	if b.Kind == "blob" {
		return "FormBlob"
	}
	kind := map[string]string{"path": "Path", "query": "Query", "form": "Form"}[b.Kind]
	typ := map[string]string{
		"string":   "String",
		"[]string": "Strings",
		"bool":     "Bool",
		"int":      "Int",
		"int64":    "Int64",
		"float64":  "Float64",
	}[b.Type]
	return kind + typ
}

// hasBucket reports whether the service's package declares a bucket —
// the signal to mount the local signed-URL endpoint.
// hasCron reports whether any cron handler runs in this service — it
// then carries the /_tako/cron dispatch route Cloud Scheduler targets.
func hasCron(g *analyzer.AppGraph, svc analyzer.Service) bool {
	for _, h := range g.Handlers {
		if h.Service == svc.Name && h.Kind == "cron" {
			return true
		}
	}
	return false
}

func hasBucket(g *analyzer.AppGraph, svc analyzer.Service) bool {
	for _, r := range g.Resources {
		if r.Package == svc.Package && r.Kind == "bucket" {
			return true
		}
	}
	return false
}

// hasResources reports whether the service's package declares resources
// needing a booted backend.
func hasResources(g *analyzer.AppGraph, svc analyzer.Service) bool {
	for _, r := range g.Resources {
		if r.Package == svc.Package {
			return true
		}
	}
	return false
}

// muxPattern maps a declared route to its ServeMux pattern. A declared
// "GET /" means THE home page, but to the mux "GET /" is the method
// catch-all — it would swallow every GET (assets, templates/) away
// from the site. "{$}" is the mux's exact-root marker.
func muxPattern(route string) string {
	if strings.HasSuffix(route, " /") {
		return route + "{$}"
	}
	return route
}

// siteOptionsLiteral renders the SiteOptions struct fields for the
// generated mount — readable, like everything in this file.
func siteOptionsLiteral(site *analyzer.Resource) string {
	var parts []string
	if site.SPA {
		parts = append(parts, "SPA: true")
	}
	if site.DevProxy != "" {
		parts = append(parts, fmt.Sprintf("DevProxy: %q", site.DevProxy))
	}
	if len(site.Redirects) > 0 {
		var pairs []string
		for _, r := range site.Redirects {
			pairs = append(pairs, fmt.Sprintf("%q: %q", r.From, r.To))
		}
		parts = append(parts, "Redirects: map[string]string{"+strings.Join(pairs, ", ")+"}")
	}
	if site.TrustedHTML {
		parts = append(parts, "TrustedHTML: true")
	}
	if site.NotFound != "" {
		parts = append(parts, fmt.Sprintf("NotFound: %q", site.NotFound))
	}
	return strings.Join(parts, ", ")
}

// asyncOnly reports whether every handler of the service is async (worker
// or subscriber) — no main is generated for it yet.
func asyncOnly(g *analyzer.AppGraph, svc analyzer.Service) bool {
	any := false
	for _, h := range g.Handlers {
		if h.Service != svc.Name {
			continue
		}
		any = true
		if h.Kind != "worker" && h.Kind != "subscribe" {
			return false
		}
	}
	return any
}

func needsDecode(h analyzer.Handler) bool {
	return h.ReqType != "" && (h.HasBody || len(h.Bindings) > 0)
}

// fallible reports whether any non-body binding can fail (string and
// []string bindings cannot; blob and parsed bindings can).
func fallible(h analyzer.Handler) bool {
	for _, b := range h.Bindings {
		if !infallibleBinding(b) {
			return true
		}
	}
	return false
}

// infallibleBinding reports whether a binding assigns without an error
// check. Text arrives as text: there is nothing to parse and so nothing
// that can fail to parse.
func infallibleBinding(b analyzer.Binding) bool {
	return b.Kind != "blob" && (b.Type == "string" || b.Type == "[]string")
}

func decodeName(h analyzer.Handler) string {
	return "decode" + analyzer.ShortVar(h)
}

// pkgAlias is the import alias for the service's user package in
// generated code: the package's OWN name, which is what the rest of
// the graph already calls it (Handler.Var is "<package>.<Var>") and
// which is an identifier by definition.
//
// It is not the last segment of the import path. That segment is not
// necessarily a Go identifier — `github.com/org/my-service` is the
// ordinary way to name a repository, and `my-service
// "github.com/org/my-service"` is a parse error at the hyphen — and
// even when it parses, spelling the module path through every
// generated reference (`tako_example_hello.GreetReq`) makes the output
// harder to read than the app it was generated from.
func pkgAlias(g *analyzer.AppGraph, svc analyzer.Service) string {
	for _, h := range g.Handlers {
		if h.Package != svc.Package {
			continue
		}
		if i := strings.Index(h.Var, "."); i > 0 {
			if name := h.Var[:i]; token.IsIdentifier(name) {
				return name
			}
		}
	}
	return aliasFromPath(svc.Package)
}

// aliasFromPath is the fallback for a service with no handler to read a
// package name from: the last path segment, forced into an identifier.
func aliasFromPath(path string) string {
	seg := path
	if i := strings.LastIndex(seg, "/"); i >= 0 {
		seg = seg[i+1:]
	}
	var b strings.Builder
	for _, r := range seg {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '_':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	alias := b.String()
	if alias == "" || alias[0] >= '0' && alias[0] <= '9' {
		alias = "pkg" + alias
	}
	if token.IsKeyword(alias) {
		alias += "_"
	}
	return alias
}

// remoteCallee is one cross-service call target this service's
// handlers reach (§2.12): its transport is registered at boot from the
// deploy-injected URL, so Call goes over the wire in the cloud and
// stays direct everywhere else.
type remoteCallee struct {
	handler analyzer.Handler
	service string // callee service name
}

// remoteCallees lists svc's cross-service call targets, in stable order.
func remoteCallees(g *analyzer.AppGraph, svc analyzer.Service) []remoteCallee {
	svcOf := map[string]string{}
	byVar := map[string]analyzer.Handler{}
	for _, h := range g.Handlers {
		svcOf[h.Var] = h.Service
		byVar[h.Var] = h
	}
	seen := map[string]bool{}
	var out []remoteCallee
	for _, e := range g.Edges {
		if e.Kind != "call" || svcOf[e.From] != svc.Name || svcOf[e.To] == svc.Name || seen[e.To] {
			continue
		}
		seen[e.To] = true
		out = append(out, remoteCallee{handler: byVar[e.To], service: svcOf[e.To]})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].handler.Var < out[j].handler.Var })
	return out
}

// remoteCallBlock renders the transport registrations. Blob endpoints
// cannot ride the JSON wire and are skipped with a visible comment.
func remoteCallBlock(callees []remoteCallee) (string, bool) {
	var b strings.Builder
	usesNetURL := false
	b.WriteString("\t// Cross-service calls (§2.12): remote transports for this service's\n")
	b.WriteString("\t// callees, wired from deploy-injected URLs. Locally nothing is\n")
	b.WriteString("\t// injected — dev, tests, and co-located packages stay direct\n\t// in-process, breakpoints and all.\n")
	for _, c := range callees {
		h := c.handler
		if h.ResBlob || hasBlobBinding(h) {
			fmt.Fprintf(&b, "\t// %s is not remotely callable: blobs do not ride the JSON call wire.\n", h.Var)
			continue
		}
		envVar := "TAKO_CALLEE_" + strings.ToUpper(strings.ReplaceAll(c.service, "-", "_"))
		method, path, _ := strings.Cut(h.Route, " ")
		pathExpr, query, needsURL := remotePathExpr(path, h.Bindings)
		usesNetURL = usesNetURL || needsURL
		fmt.Fprintf(&b, "\tif base := os.Getenv(%q); base != \"\" {\n", envVar)
		fmt.Fprintf(&b, "\t\truntime.RegisterRemoteCall(%q, %q, func(ctx tako.Ctx, req %s) (%s, error) {\n",
			h.Package, h.Route, h.ReqRef, h.ResRef)
		fmt.Fprintf(&b, "\t\t\tpath := %s\n", pathExpr)
		b.WriteString(query)
		fmt.Fprintf(&b, "\t\t\treturn runtime.RemoteJSON[%s, %s](ctx, %q, base, %q, path, req)\n",
			h.ReqRef, h.ResRef, c.service, method)
		b.WriteString("\t\t})\n\t}\n")
	}
	b.WriteString("\n")
	return b.String(), usesNetURL
}

func hasBlobBinding(h analyzer.Handler) bool {
	for _, b := range h.Bindings {
		if b.Kind == "blob" {
			return true
		}
	}
	return false
}

// remotePathExpr renders the callee path as a Go expression with path
// params interpolated from req fields, plus query-string lines.
func remotePathExpr(path string, bindings []analyzer.Binding) (expr, queryLines string, usesNetURL bool) {
	fieldOfParam := map[string]string{}
	var queryBindings []analyzer.Binding
	for _, b := range bindings {
		switch b.Kind {
		case "path":
			fieldOfParam[b.Name] = b.Field
		case "query":
			queryBindings = append(queryBindings, b)
		}
	}
	var parts []string
	rest := path
	for {
		i := strings.IndexByte(rest, '{')
		if i < 0 {
			break
		}
		j := strings.IndexByte(rest[i:], '}')
		if j < 0 {
			break
		}
		if i > 0 {
			parts = append(parts, fmt.Sprintf("%q", rest[:i]))
		}
		param := rest[i+1 : i+j]
		field := fieldOfParam[strings.TrimSuffix(param, "...")]
		if strings.HasSuffix(param, "...") {
			// Wildcards span segments; their slashes must survive.
			parts = append(parts, fmt.Sprintf("fmt.Sprint(req.%s)", field))
		} else {
			parts = append(parts, fmt.Sprintf("neturl.PathEscape(fmt.Sprint(req.%s))", field))
			usesNetURL = true
		}
		rest = rest[i+j+1:]
	}
	if rest != "" || len(parts) == 0 {
		parts = append(parts, fmt.Sprintf("%q", rest))
	}
	expr = strings.Join(parts, " + ")
	if len(queryBindings) > 0 {
		usesNetURL = true
		var q strings.Builder
		q.WriteString("\t\t\tqs := neturl.Values{}\n")
		for _, b := range queryBindings {
			if b.Type == "[]string" {
				// Add, not Set: the whole point of the field is that it
				// repeats, and Set would collapse it to one value.
				fmt.Fprintf(&q, "\t\t\tfor _, v := range req.%s {\n\t\t\t\tqs.Add(%q, v)\n\t\t\t}\n", b.Field, b.Name)
				continue
			}
			fmt.Fprintf(&q, "\t\t\tqs.Set(%q, fmt.Sprint(req.%s))\n", b.Name, b.Field)
		}
		q.WriteString("\t\t\tpath += \"?\" + qs.Encode()\n")
		queryLines = q.String()
	}
	return expr, queryLines, usesNetURL
}

// statusOf finds the status page the service's package declares, if
// any. Like the site, it belongs to the package, so an async service
// of the same package registers it too — a worker can answer a 404 on
// its push endpoint like anything else.
func statusOf(g *analyzer.AppGraph, svc analyzer.Service) *analyzer.Resource {
	for i, r := range g.Resources {
		if r.Kind == "status" && r.Package == svc.Package {
			return &g.Resources[i]
		}
	}
	return nil
}
