package codegen

// The test harness (AB2): the app's real HTTP surface, generated.
//
// Templates compile into the generated service, so a test that asserts
// real HTML has to mount the same handlers the generated main mounts.
// Nothing offered that, so apps hand-mirrored codegen — 874 lines in the
// app that drove this, 1,052 in tako's own journal example — and the
// mirror drifted: a blob route, a status page, and four write routes
// that no test drove because nobody noticed they were never mounted.
// Mount OPTIONS were mirrored by nothing at all, so declaring
// Route{MaxAge} changed the real service and changed no test.
//
// This file emits the same mounts from the same emitter (writeMounts),
// into a file that declares the APP's package, and registers it with the
// runtime. `tako test` maps it in with go's -overlay, so generated code
// stays under .tako/gen/ and never touches the source tree.

import (
	"fmt"
	"strings"

	"github.com/gsandoval/tako/internal/routes"
	"github.com/gsandoval/tako/pkg/analyzer"
)

// harnessFile is the generated file's name inside the app package. The
// tako_ prefix keeps it recognisable in a stack trace, and _test.go
// keeps it out of the production build entirely.
const harnessFile = "tako_harness_test.go"

// harnessDir is the subdirectory the harness is written to, and it has
// to be a subdirectory: the file declares the APP's package, and a
// directory holding both it and main.go is two packages in one place —
// `go build ./.tako/gen/<svc>` then fails with "found packages main and
// <app>". The image build does exactly that, which is how this was
// caught.
const harnessDir = "harness"

// serviceHarness emits the in-package test harness for one route-serving
// service, or nil when the service has no routes to mount.
func serviceHarness(g *analyzer.AppGraph, svc analyzer.Service) []byte {
	// A job or a singleton serves no requests, so there is nothing to
	// mount and nothing a test could ask for.
	if svc.Job || svc.Singleton {
		return nil
	}
	routed := false
	for _, h := range g.Handlers {
		if h.Service == svc.Name && (h.Kind == "api" || h.Kind == "page") {
			routed = true
		}
	}
	site := siteOf(g, svc)
	if !routed && site == nil {
		return nil
	}

	// The package's real NAME, not the last path segment: hello's module
	// is tako-example-hello and its package is `hello`, so a path-derived
	// name emitted `package tako-example-hello` — which parses as
	// `package tako` and then fails on the dash. pkgAlias reads the name
	// off a declaration, which is where it is actually written down.
	pkgName := pkgAlias(g, svc)
	// os is only for the site's DirFS; an API-only app has no site, and
	// an unused import does not compile.
	osImport := ""
	if site != nil {
		osImport = "\n\t\"os\""
	}
	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by tako. DO NOT EDIT.
//
// The test harness for service %s: the same mounts the generated main
// makes, in a file that lives in this app's package so a test can reach
// them. tako.NewTestApp(t).Handler() returns what this builds.
//
// It is mapped into the package by `+"`tako test`"+` with go's -overlay, so
// this file is real and readable and is never written into your source
// tree. Plain `+"`go test`"+` does not see it, and app.Handler() says so.
package %s

import (
	"net/http"%s

	runtime "github.com/gsandoval/tako/pkg/runtime"
)

func init() {
	runtime.RegisterTestMux(takoTestMux)
}

// takoTestMux mounts this service exactly as the deployed one is
// mounted: the same wrappers, the same generated binders, the same
// RequireAuth / RequirePolicy / CacheFor options, and the site handler
// last so a mistyped URL is a SITE 404 rather than the mux's bare one.
//
// What it deliberately leaves out is everything that is not a request:
// runtime.Boot (NewTestApp booted the backends), the async registrations
// (NewTestApp wires every worker and subscriber from the declarations),
// and the dev bar.
func takoTestMux() http.Handler {
`, svc.Name, pkgName, osImport)

	if hasAuth(g) || hasBucket(g, svc) || hasCron(g, svc) {
		b.WriteString("\ttakoMux := http.NewServeMux()\n")
		if hasAuth(g) {
			fmt.Fprintf(&b, "\ttakoMux.Handle(%q, runtime.SessionHandler(%s))\n", routes.PatternSession, providerArgs(g))
			fmt.Fprintf(&b, "\ttakoMux.Handle(%q, runtime.SignOutHandler())\n", routes.PatternSignOut)
			fmt.Fprintf(&b, "\ttakoMux.Handle(%q, runtime.SignInPage(%s))\n", routes.PatternSignIn, providerArgs(g))
			if len(g.Roles) > 0 {
				fmt.Fprintf(&b, "\truntime.RegisterRoles(%s)\n", quotedList(g.Roles))
			}
		}
		if hasBucket(g, svc) {
			fmt.Fprintf(&b, "\ttakoMux.Handle(%q, runtime.SignedURLHandler())\n", routes.PatternSigned)
		}
		if hasCron(g, svc) {
			fmt.Fprintf(&b, "\ttakoMux.Handle(%q, runtime.CronDispatch())\n", routes.PatternCron)
		}
		b.WriteString("\n")
	} else {
		b.WriteString("\ttakoMux := http.NewServeMux()\n\n")
	}

	if sp := statusOf(g, svc); sp != nil {
		fmt.Fprintf(&b, "\truntime.RegisterStatusPage(%s)\n\n", analyzer.ShortName(sp.Var))
	}
	b.WriteString("\tmux := http.NewServeMux()\n\n")
	if site != nil {
		// The app's own site directory, read from disk — a test runs in
		// the package dir, and the embedded copy the main builds is a
		// build-time artifact this does not need.
		fmt.Fprintf(&b, "\tsiteRoot := os.DirFS(%q)\n", strings.TrimPrefix(site.Name, "./"))
		fmt.Fprintf(&b, "\truntime.RegisterSiteTemplates(siteRoot, runtime.SiteOptions{%s})\n", siteOptionsLiteral(site))
		fmt.Fprintf(&b, "\tmux.Handle(\"/\", runtime.SiteHandler(siteRoot, runtime.SiteOptions{%s}))\n\n", siteOptionsLiteral(site))
	}

	decoders := writeMounts(&b, g, svc, "")
	b.WriteString("\treturn runtime.Reserved(takoMux, mux)\n}\n")
	for _, h := range decoders {
		writeDecoder(&b, "", h)
	}
	return []byte(b.String())
}
